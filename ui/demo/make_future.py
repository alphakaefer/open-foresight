#!/usr/bin/env python3
"""Generate ui/demo/future.json: ILLUSTRATIVE future values for the UI's Future mode.

These are NOT data and NOT model forecasts. Each value is the current value multiplied by a seeded random
factor (0.75 to 1.25); scenario probabilities move by up to 10 points. They exist only to show how the colour
coding and readouts behave when future values differ. The UI labels every value as illustrative.

    python3 ui/demo/make_future.py
"""
import json
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SEED = 2032
rng = random.Random(SEED)
factor = lambda: rng.uniform(0.75, 1.25)

params = json.loads((ROOT / "ui/parameters.json").read_text())
wissen = json.loads((ROOT / "radar/snapshot/wissensstand.json").read_text())
regional = json.loads((ROOT / "radar/regional/regional.json").read_text())
briefing = json.loads((ROOT / "domains/energy-transition/briefing.json").read_text())
series = {r["id"]: r for r in wissen["reihen"]}

out = {"_note": "ILLUSTRATIVE future values, generated by ui/demo/make_future.py (seed %d). Not data, not forecasts." % SEED,
       "series": {}, "model": {}, "regional": {}}

for p in params["params"]:
    if p["kind"] == "series":
        last = series[p["series"]]["punkte"][-1]["wert"]
        out["series"][p["id"]] = {"value": round(last * factor(), 2), "unit": p["unit"]}

# scenario probability (share of mass in scenarios with energy price above neutral), 2032
rows = briefing["scenarios"]["rows"]
today = sum(r["p_today"]["2032"] for r in rows if r["regime"]["energy_price"] > 0)
out["model"]["regime_dear"] = {"value": round(min(100, max(0, today + rng.uniform(-10, 10))))}

for ds_id, ds in regional["datasets"].items():
    out["regional"][ds_id] = {k: {"v": round(e["v"] * factor(), 3), "p": "2032 (illustrative)"} for k, e in ds["values"].items()}

(ROOT / "ui/demo/future.json").write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n")
print("wrote ui/demo/future.json:", len(out["series"]), "series,", len(out["regional"]), "regional datasets")
