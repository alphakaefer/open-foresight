"""Generate backtest/indicators/SERIES.md from the headers of the series CSVs (no hand-typed values).

    python3 backtest/list_series.py > backtest/indicators/SERIES.md
"""
from __future__ import annotations

import csv
from pathlib import Path

DIR = Path(__file__).resolve().parent / "indicators" / "reihen"
KEYS = {"Reihe": "series", "Quelle": "source", "Adresse": "url", "Abruf": "fetched", "Aufbereitung": "processing",
        "Nutzung": "use"}


def header(path: Path) -> dict:
    out = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.startswith("# "):
            break
        key, _, value = line[2:].partition(": ")
        if key in KEYS:
            out[KEYS[key]] = value.strip()
    return out


def values(path: Path) -> list:
    rows = [r for r in csv.reader(l for l in path.read_text(encoding="utf-8").splitlines() if not l.startswith("#"))]
    return rows[1:]


def main() -> None:
    print("# Backtest series\n")
    print("Generated by `backtest/list_series.py` from the CSV headers in `backtest/indicators/reihen/`. "
          "Header texts are the German originals. Data belong to their publishers; cite the source.\n")
    print("| file | series (original label) | first | last | values | source | fetched | url |")
    print("|---|---|---|---|---|---|---|---|")
    for p in sorted(DIR.glob("*.csv")):
        h, v = header(p), values(p)
        print(f"| `{p.name}` | {h.get('series', '')} | {v[0][0] if v else ''} | {v[-1][0] if v else ''} | {len(v)} | "
              f"{h.get('source', '')} | {h.get('fetched', '')} | {h.get('url', '')} |")
    print("\nProcessing notes (German originals), as in the radar collector:\n")
    for p in sorted(DIR.glob("*.csv")):
        h = header(p)
        print(f"- `{p.stem}`: {h.get('processing', '')}. {h.get('use', '')}")


if __name__ == "__main__":
    main()
