"""Generate radar/SOURCES.md from a radar snapshot (no hand-typed numbers).

    python3 radar/list_sources.py [radar/snapshot/wissensstand.json] > radar/SOURCES.md
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

KIND = {"nachricht": "news", "forschung": "research", "statistik": "statistics", "messung": "measurement",
        "umfrage": "survey", "parlament": "parliament"}
STEEP = {"technologie": "technology", "wirtschaft": "economy", "politik": "politics", "gesellschaft": "society",
         "umwelt": "environment", "wissenschaft": "science", "werte": "values"}


def main(path: str) -> None:
    ws = json.loads(Path(path).read_text(encoding="utf-8"))
    counts = Counter(s["quelle"] for s in ws.get("signale", []))
    print("# Radar data sources\n")
    print(f"Generated by `radar/list_sources.py` from the snapshot dated **{ws['stand']}**. "
          "Do not edit by hand – regenerate.\n")
    print("## Sources\n")
    print("| id | name | type | items in snapshot | last fetch ok | url |")
    print("|---|---|---|---|---|---|")
    for q in ws["quellen"]:
        ok = "yes" if q.get("ok") else f"no ({q.get('fehler', '')})"
        print(f"| `{q['id']}` | {q['name']} | {KIND.get(q['art'], q['art'])} | "
              f"{counts.get(q['id'], q.get('anzahl', 0))} | {ok} | {q.get('url', '')} |")
    print("\n## Time series (used by the early-warning indicators)\n")
    print("| series id | title (original) | unit | source | points | latest | url |")
    print("|---|---|---|---|---|---|---|")
    for r in ws["reihen"]:
        pts = r.get("punkte", [])
        last = f"{pts[-1]['t']}: {pts[-1]['wert']}" if pts else "–"
        print(f"| `{r['id']}` | {r['titel']} | {r.get('einheit', '')} | {r.get('quelleName', r.get('quelle', ''))} | "
              f"{len(pts)} | {last} | {r.get('url', '')} |")
    print("\n## Topic areas (STEEP)\n")
    for steep, n in Counter(s.get("steep") for s in ws.get("signale", [])).most_common():
        print(f"- {STEEP.get(steep, steep)}: {n} news/research items")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(Path(__file__).parent / "snapshot" / "wissensstand.json"))
